def main():
    base_dir = Path("d:/startup/resume/skills")
    base_dir.mkdir(exist_ok=True)
    created = 0
    for name, (desc, content) in SKILLS.items():
        skill_dir = base_dir / name
        skill_dir.mkdir(exist_ok=True)
        skill_md = skill_dir / "SKILL.md"
        full_text = f"---\nname: {name}\ndescription: {desc}\n---\n\n{content}\n"
        skill_md.write_text(full_text, encoding="utf-8")
        created += 1
    print(f"Successfully generated {created} SKILL.md files in {base_dir}")

if __name__ == "__main__":
    main()
